async function main() {
  console.log("═══════════════════════════════════════");
  console.log("📥 中文海关底库灌浆启动");
  console.log("═══════════════════════════════════════");

  // Step 1: Clear existing data
  console.log("⚠️ 正在清空 hs_codes 表...");
  await pool.query("TRUNCATE TABLE hs_codes CASCADE");
  console.log("✅ 表已清空");

  // Step 2: Build rows from PRODUCTS list
  console.log("🚀 开始批量生成并灌入数据库...");
  
  const rows: any[] = [];
  
  // First add all chapter-level entries (2-digit)
  for (const [chap, chapName] of CHAPTERS) {
    rows.push({
      code: chap + "00",
      level: 4,
      parentId: null,
      description: `${chapName}`,
      descriptionEn: `Chapter ${parseInt(chap)}`,
      taxRate: null,
      notes: `第${parseInt(chap)}章 - ${chapName}`,
      category: chapName,
      isActive: true,
    });
  }
  
  // Then add all product-level entries (4-digit)
  for (const [headCode, descCn] of PRODUCTS) {
    const chap = headCode.substring(0, 2);
    const chapterName = CHAPTERS.find(c => c[0] === chap)?.[1] || "其他类别";
    
    rows.push({
      code: headCode,
      level: 6,
      parentId: null,
      description: descCn,
      descriptionEn: descCn,
      taxRate: null,
      notes: `第${parseInt(chap)}章 - ${chapterName}`,
      category: chapterName,
      isActive: true,
    });
  }

  console.log(`📦 共准备 ${rows.length} 条记录`);

  // Step 3: Batch insert
  const batchSize = 500;
  let inserted = 0;
  
  for (let i = 0; i < rows.length; i += batchSize) {
    const batch = rows.slice(i, i + batchSize);
    const values = batch.map((_, idx) => {
      const base = idx * 11;
      return `($${base + 1}, $${base + 2}, $${base + 3}, $${base + 4}, $${base + 5}, $${base + 6}, $${base + 7}, $${base + 8}, $${base + 9}, $${base + 10}, $${base + 11})`;
    }).join(", ");
    
    const flatValues = batch.flatMap(r => {
      const id = `hs_${r.code}`;
      const now = new Date().toISOString();
      return [
        id, r.code, r.level, r.parentId, r.description, r.descriptionEn,
        r.category, r.taxRate, r.notes, r.isActive, now
      ];
    });
    
    await pool.query(
      `INSERT INTO hs_codes (id, code, level, "parentId", description, "descriptionEn", category, "taxRate", notes, "isActive", "updatedAt") 
       VALUES ${values} ON CONFLICT (code) DO NOTHING`,
      flatValues
    );
    
    inserted += batch.length;
    if (inserted % 1000 === 0 || inserted === rows.length) {
      console.log(`   ✅ 已灌入 ${inserted}/${rows.length} 条`);
    }
  }

  console.log(`\n✅ 中文底库灌浆完成！共灌入 ${inserted} 条。`);
  const result = await pool.query("SELECT COUNT(*) FROM hs_codes");
  console.log(`📈 当前 HsCode 表总量: ${result.rows[0].count}`);
  
  await pool.end();
}

main().catch((e) => {
  console.error("💥 导入失败:", e.message);
  process.exit(1);
});
